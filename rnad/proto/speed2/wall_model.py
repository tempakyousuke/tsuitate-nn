"""F10: pipeline の1更新の壁時計の粗い模型（推測。docs/rl-learning-speed.md「さらに速くする」の 9.3。学習には使っていない）。

    python rnad/proto/speed2/wall_model.py

W = 段階平均の max(C', U')。C' = 収集の単独時間 + 取り合いの上乗せ dc、U' = 更新の単独時間 + 取り合いの上乗せ du。
補間中（α<1、段階の前半）と α=1（後半）を半々で平均する。数値は調べた時点の実測・模型から:
  基準: 1更新 7.9s（v6→v7 平均、実測）、補間中の A/B で 更新 7.3 + 待ち 1.4（実測）、
  単独: 収集 6.2〜7.2（実測）、更新 packed 5.57（bench, α=0 = α=1 と同じ計算量, 実測）/ 6.3（学習ログ, 補間中, 実測）
下の表（STEPS）の 2行目以降は**試作を入れた後の見込み**（CPU の実測から換算した推測。各行は前の行の上に積む）。
+3 の行は BN の畳み込みへの畳み込みも含めた最初の見積もりで、検証で「eager では効果≈0」と分かったので悲観側
（上限）寄りに読む（docs は S3 の後 約5.8秒を中心にした）。ゲーム用 PC で測った値（stage_log.py の α<1 / α=1 の busy・更新の中央値、
bench_update.py の単独の秒）で STEPS を書き換えれば、律速がどこで入れ替わるかを引き直せる
"""


def W(Cr, Ca, Ur, Ua, dc, du):
    ramp = max(Cr + dc, Ur + du)
    a1 = max(Ca + dc, Ua + du)
    return 0.5 * (ramp + a1), ramp, a1


# (名前, 収集 単独 [lo,hi], 更新 補間中 [lo,hi], 更新 α=1 [lo,hi], dc [lo,hi], du [lo,hi])
STEPS = [
    ("今（較正）", (6.2, 7.2), (6.3, 6.4), (5.6, 5.6), (1.5, 2.5), (1.0, 1.0)),
    ("+1 収集のCPU経路", (2.6, 3.0), (6.3, 6.4), (5.6, 5.6), (1.0, 1.5), (0.6, 1.0)),
    ("+2 batch をGPU常駐・同期除去", (2.4, 2.8), (5.3, 5.9), (4.6, 5.1), (1.0, 1.5), (0.6, 0.9)),
    ("+3 融合（＋BN畳み込み）", (2.3, 2.7), (4.1, 5.2), (3.5, 4.5), (1.0, 1.5), (0.6, 0.9)),
    ("+4a fp16 pass1+行動", (1.9, 2.3), (3.3, 4.4), (3.0, 4.0), (0.6, 1.0), (0.4, 0.5)),
    ("+4b fp16 pass2 も", (1.9, 2.3), (2.4, 3.5), (2.1, 3.1), (0.6, 1.0), (0.4, 0.5)),
]
BASE = 7.9


def main():
    prev = None
    for name, C, Ur, Ua, dc, du in STEPS:
        # 楽観 = 各量の下限、悲観 = 上限
        lo, ramp_lo, a1_lo = W(C[0], C[0], Ur[0], Ua[0], dc[0], du[0])
        hi, ramp_hi, a1_hi = W(C[1], C[1], Ur[1], Ua[1], dc[1], du[1])
        who = "収集" if C[1] + dc[1] >= Ua[1] + du[1] else "更新"
        line = f"{name:24s} W = {lo:.2f}〜{hi:.2f}s/更新  今比 {BASE / hi:.2f}〜{BASE / lo:.2f}倍  α=1 の律速 {who}"
        if prev is not None:
            r = sorted((prev[0] / lo, prev[1] / hi))
            line += f"  直前比 {r[0]:.2f}〜{r[1]:.2f}倍"
        print(line)
        prev = (lo, hi)


if __name__ == "__main__":
    main()
